/**
 * 업종별 상세 페이지의 기본(코드) 콘텐츠 — slug로 키잉한다.
 * DB `industries.content`(관리자 오버라이드)가 있으면 그쪽이 우선, 없으면 여기 값을 쓴다.
 * 모든 예시는 '가상 예시'로만 제시한다(실제 고객 성과·후기로 오인되지 않게).
 * 한국어 기준(서비스 기본 로케일 ko) — 영어 로케일에서도 본문은 한국어로 노출된다.
 */

export type ChannelKind = "site" | "blog" | "card" | "video";

export interface IndustryFlowStep {
  title: string;
  desc: string;
}
export interface IndustryChannel {
  kind: ChannelKind;
  title: string;
  desc: string;
}
export interface IndustryFaq {
  q: string;
  a: string;
}
export interface IndustryContent {
  /** ① 전용 제목·설명 */
  headline: string;
  sub: string;
  /** ② 대표적인 고민 3가지 */
  concerns: string[];
  /** ③ 활용 흐름(실제 정보 입력 → 초안 제작 → 검토·발행) */
  flow: IndustryFlowStep[];
  /** ④ 채널별 활용 예시 */
  channels: IndustryChannel[];
  /** ⑤ 입력 정보 예시 */
  inputs: string[];
  /** ⑤ 콘텐츠 주제 예시 */
  topics: string[];
  /** ⑥ 가상 예시 샘플(항상 '가상 예시'로 표시) */
  sample: { title: string; body: string };
  /** ⑦ 업종별 FAQ */
  faq: IndustryFaq[];
  /** 하위 분류(선택) — 초기 화면에 강제하지 않고 안내만 */
  subtypes?: string[];
}

const CHANNEL_LABEL: Record<ChannelKind, string> = {
  site: "홈페이지·랜딩",
  blog: "블로그",
  card: "SNS 카드뉴스",
  video: "영상",
};
export function channelLabel(kind: ChannelKind): string {
  return CHANNEL_LABEL[kind];
}

// 공통 흐름(세 단계)을 업종 예시로 채워 반환. 설명만 업종별로 달라진다.
function flow(
  input: string,
  draft: string,
  review: string,
): IndustryFlowStep[] {
  return [
    { title: "실제 사업 정보 입력", desc: input },
    { title: "콘텐츠 초안 제작", desc: draft },
    { title: "검토·발행", desc: review },
  ];
}

